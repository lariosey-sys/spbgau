def wrap_block(fig, x, y, text, width=118, fontsize=11, leading=0.0185,
               color="#222222", bold_first=False, family="DejaVu Sans"):
    """Рисует абзацный текст с переносами. Возвращает итоговый y."""
    for para in text.split("\n"):
        if para.strip() == "":
            y -= leading * 0.7
            continue
        weight = "normal"
        fs = fontsize
        col = color
        ind = x
        if para.startswith("§ "):           # заголовок секции
            para = para[2:]; weight = "bold"; fs = fontsize + 2.0; col = GREEN
        elif para.startswith("• "):          # маркер
            ind = x + 0.012
        elif para.startswith("» "):          # вывод-акцент
            para = para[2:]; weight = "bold"; col = ACCENT
        lines = textwrap.wrap(para, width=width) or [""]
        for i, ln in enumerate(lines):
            prefix = ""
            xx = ind
            if para_was_bullet := para.startswith("• ") and i == 0:
                pass
            fig.text(xx, y, ln, fontsize=fs, fontweight=weight, color=col,
                     family=family, va="top")
            y -= leading
        y -= leading * 0.25
    return y


def table_axes(fig, rect, df, col_labels=None, fontsize=8.5, header_color=GREEN,
               col_widths=None, highlight_rows=None, cell_fmt=None, title=None):
    ax = fig.add_axes(rect)
    ax.axis("off")
    if title:
        ax.set_title(title, loc="left", fontsize=12, color=GREEN, pad=8)
    data = df.copy()
    cols = col_labels or list(data.columns)
    cells = []
    for _, row in data.iterrows():
        out = []
        for c in data.columns:
            v = row[c]
            if cell_fmt and c in cell_fmt and pd.notna(v):
                out.append(cell_fmt[c](v))
            elif isinstance(v, float):
                out.append("—" if pd.isna(v) else f"{v:.2f}".rstrip("0").rstrip("."))
            else:
                out.append("—" if pd.isna(v) else str(v))
        cells.append(out)
    t = ax.table(cellText=cells, colLabels=cols, loc="center",
                 cellLoc="center", colWidths=col_widths)
    t.auto_set_font_size(False)
    t.set_fontsize(fontsize)
    t.scale(1, 1.32)
    for (r, c), cell in t.get_celld().items():
        cell.set_edgecolor("#cccccc")
        cell.set_linewidth(0.5)
        if r == 0:
            cell.set_facecolor(header_color)
            cell.get_text().set_color("white")
            cell.get_text().set_fontweight("bold")
            cell.set_height(cell.get_height() * 1.15)
        else:
            cell.set_facecolor("#ffffff" if r % 2 else "#f3f8f3")
            if highlight_rows and (r - 1) in highlight_rows:
                cell.set_facecolor("#fff3e0")
    return ax


def bars(ax, labels, values, colors, title, ylabel, fmt="{:.1f}", rot=0,
         annotate=True, baseline=None):
    x = np.arange(len(labels))
    b = ax.bar(x, values, color=colors, edgecolor="#33333355", width=0.72)
    ax.set_xticks(x); ax.set_xticklabels(labels, rotation=rot,
                                         ha="center" if rot == 0 else "right")
    ax.set_title(title); ax.set_ylabel(ylabel)
    if annotate:
        for xi, v in zip(x, values):
            if pd.notna(v):
                ax.text(xi, v, fmt.format(v), ha="center", va="bottom", fontsize=8.5)
    if baseline is not None:
        ax.axhline(baseline, color=ACCENT, lw=1.0, ls="--")
    ax.margins(y=0.16)
    return b


